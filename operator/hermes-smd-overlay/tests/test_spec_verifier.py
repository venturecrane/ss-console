SLUG = "seat-alpha"
FIXTURE = Path(__file__).parent / "fixtures" / "seat_spec"


class Missing(Exception):
    response = {"Error": {"Code": "NoSuchKey"}}


class FakeS3:
    def __init__(self, objects: dict[str, bytes]):
        self.objects = objects
        self.broken = False
        self.heads = 0

    def head_object(self, *, Bucket, Key):  # noqa: N803 -- boto3's keyword names
        self.heads += 1
        if Key not in self.objects:
            raise Missing()
        return {"ETag": hashlib.sha256(self.objects[Key]).hexdigest()}

    def get_object(self, *, Bucket, Key):  # noqa: N803 -- boto3's keyword names
        if self.broken:
            raise RuntimeError("connection reset")
        if Key not in self.objects:
            raise Missing()
        return {"Body": io.BytesIO(self.objects[Key])}


def canonical(value: object) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def make_spec(**over) -> dict:
    spec = {
        "schema_version": 1,
        "slug": SLUG,
        "compiled_from": "1" * 40,
        "customer_yaml": {
            "key": f"vaults/{SLUG}/customer.yaml",
            "sha256": hashlib.sha256(b"cfg\n").hexdigest(),
        },
        "lane_proofs": None,
        "lanes": {},
        "skills": None,
        "requires": {
            "skills": ["matter-reader"],
            "image": ["skill:matter-reader"],
            "capabilities": {"paths": [], "tools": [], "verbs": [], "action_classes": []},
            "lane_schema_digests": {},
        },
    }
    spec.update(over)
    return spec


def publish(
    objects: dict[str, bytes],
    spec: dict,
    key: Ed25519PrivateKey,
    *,
    sign_bytes: bytes | None = None,
) -> str:
    data = canonical(spec)
    sha = hashlib.sha256(data).hexdigest()
    objects[f"fleet/specs/{SLUG}/{sha}.json"] = data
    objects[f"vaults/{SLUG}/spec-pointer.json"] = json.dumps(
        {
            "spec_sha256": sha,
            "key_id": key_id_of(key.public_key()),
            "signature": base64.b64encode(key.sign(sign_bytes or data)).decode(),
        }
    ).encode()
    return sha


@pytest.fixture
def image(tmp_path: Path) -> ImageView:
    manifest = tmp_path / "image-manifest.json"
    manifest.write_text(
        json.dumps(
            {
                "schema_version": 1,
                "skills": {"matter-reader": {"pin": "abc123", "files": ["SKILL.md"]}},
            }
        )
    )
    caps = tmp_path / "image-capabilities.json"
    caps.write_text(
        json.dumps({"tools": ["email_search"], "verbs": [], "action_classes": ["read"]})
    )
    return ImageView(manifest_path=manifest, capabilities_path=caps)


def run(
    objects: dict[str, bytes],
    key: Ed25519PrivateKey,
    image: ImageView,
    running: bytes | None = b"cfg\n",
):
    s3 = FakeS3(objects)

    def fetch(k: str) -> bytes | None:
        return objects.get(k)

    return judge(
        slug=SLUG,
        pointer_bytes=objects.get(f"vaults/{SLUG}/spec-pointer.json"),
        fetch_bytes=fetch,
        public_key=key.public_key(),
        image=image,
        running_yaml=running,
        now=1_800_000_000.0,
    ), s3


def test_a_signed_spec_the_image_can_run_verifies(image):
    key = Ed25519PrivateKey.generate()
    objects: dict[str, bytes] = {}
    sha = publish(objects, make_spec(), key)
    v, _ = run(objects, key, image)
    assert v.verdict == "verified"
    assert v.spec_sha256 == sha
    assert v.compiled_from == "1" * 40
    assert v.customer_yaml_match is True


def test_tampered_spec_bytes_fail_the_digest(image):
    key = Ed25519PrivateKey.generate()
    objects: dict[str, bytes] = {}
