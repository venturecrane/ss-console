def test_the_compiler_signed_fixture_verifies_here(image):
    pub = load_pem_public_key((FIXTURE / "seat-spec.pub").read_bytes())
    pointer = (FIXTURE / "pointer.json").read_bytes()
    spec_bytes = (FIXTURE / "spec.json").read_bytes()
    sha = json.loads(pointer)["spec_sha256"]
    v = judge(
        slug=SLUG,
        pointer_bytes=pointer,
        fetch_bytes={f"fleet/specs/{SLUG}/{sha}.json": spec_bytes}.get,
        public_key=pub,  # type: ignore[arg-type]
        image=ImageView(
            image.manifest_path,
            image.capabilities_path,
            read_bytes=lambda p: None,
        ),
        running_yaml=None,
        now=0.0,
    )
    # The signature and digest are the TS compiler's; the lane module is not in
    # this tmp image, so the only finding is the lane, which proves everything
    # before it passed.
    assert (v.verdict, v.unmet) == ("unmet_requirement", ["lane:demand"])
    assert v.key_id == json.loads(pointer)["key_id"] == key_id_of(pub)  # type: ignore[arg-type]


def test_the_state_file_is_world_readable_and_written_by_rename(tmp_path):
    key = Ed25519PrivateKey.generate()
    v = judge(
        slug=SLUG,
        pointer_bytes=None,
        fetch_bytes=dict().get,
        public_key=key.public_key(),
        image=ImageView(),
        running_yaml=None,
        now=0.0,
    )
    path = tmp_path / "smd-spec" / "state.json"
    write_state(v, path)
    assert stat.S_IMODE(path.stat().st_mode) == 0o644
    assert stat.S_IMODE(path.parent.stat().st_mode) == 0o755
    assert json.loads(path.read_text())["verdict"] == "absent"
    assert [p.name for p in path.parent.iterdir()] == ["state.json"]


class Clock:
    def __init__(self) -> None:
        self.now = 1_800_000_000.0

    def __call__(self) -> float:
        return self.now


def test_the_step_rejudges_on_a_pointer_change_or_when_due(image, tmp_path):
    key = Ed25519PrivateKey.generate()
    objects: dict[str, bytes] = {}
    publish(objects, make_spec(), key)
    clock = Clock()
    verifier = SpecVerifier(
        s3_client=FakeS3(objects),
        bucket="b",
        slug=SLUG,
        running_yaml_path=tmp_path / "customer.yaml",
        state_path=tmp_path / "state.json",
        image=image,
        public_key_loader=key.public_key,
        clock=clock,
    )
    assert verifier.step() is not None
    assert verifier.step() is None
    clock.now += REVERIFY_SECONDS
    assert verifier.step() is not None
    publish(objects, make_spec(compiled_from="2" * 40), key)
    v = verifier.step()
    assert v is not None and v.compiled_from == "2" * 40


def test_an_r2_fault_is_fetch_error_and_keeps_the_last_spec(image, tmp_path):
    key = Ed25519PrivateKey.generate()
    objects: dict[str, bytes] = {}
    sha = publish(objects, make_spec(), key)
    s3 = FakeS3(objects)
    clock = Clock()
    verifier = SpecVerifier(
        s3_client=s3,
        bucket="b",
        slug=SLUG,
        running_yaml_path=tmp_path / "customer.yaml",
        state_path=tmp_path / "state.json",
        image=image,
        public_key_loader=key.public_key,
        clock=clock,
    )
    assert verifier.step().verdict == "verified"  # type: ignore[union-attr]
    s3.broken = True
    clock.now += REVERIFY_SECONDS
    v = verifier.step()
    assert v is not None and (v.verdict, v.spec_sha256) == ("fetch_error", sha)


class ExplodingVerifier:
    def step(self):
        raise RuntimeError("verifier bug")


class NoConfigS3:
    def head_object(self, *, Bucket, Key):  # noqa: N803 -- boto3's keyword names
        raise RuntimeError("NoSuchKey")


def test_a_verifier_fault_never_reaches_the_apply_path(tmp_path):
    loop = PollLoop(
        s3_client=NoConfigS3(),
        bucket="b",
        slug=SLUG,
        volume_path=tmp_path / "customer.yaml",
        epoch_file=tmp_path / "epoch",
        audit_client=None,
        spec_verifier=ExplodingVerifier(),
    )
    # The applier carries on to its own HEAD (which finds nothing): no raise.
    assert loop.run_once() is None
