"""The root seat-spec verifier (config_applier.spec_verifier), shadow mode.

Every verdict is driven from real Ed25519 keys and real bytes: a fake S3 serves
objects from a dict, and the image is a tmp tree. The falsifiers that matter
most are the three ways a spec must NOT verify: tampered bytes, a tampered
signature, and a key this image does not carry. A spec the TS compiler signed
(tests/fixtures/seat_spec, regenerated by nothing: tests/compile-seat-spec.test.ts
re-derives its bytes) verifies here, which is the cross-language proof.
"""

