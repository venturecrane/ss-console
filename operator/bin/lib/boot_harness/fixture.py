"""The harness customer.yaml: smd-staging's shape with every reach into the world removed.

Derived, not hand-copied, so the harness boots what staging boots today (same
persona, skills, entitlements, output classes, machine size) and cannot drift
from it unnoticed. What is changed, and why:

* the slug becomes ``boot-harness`` everywhere, so no path, R2 prefix, D1
  namespace or vectorize index names staging's;
* ``connectors``, ``webhook_triggers`` and ``mcp_connector`` are dropped: the
  msgraph connector would poll staging's real test mailbox and act on it;
* every human address (roster, admins, device senders, send-as, the smd-note
  recipient) becomes an address under ``.invalid``, so no real person is
  reachable even if a send path somehow ran.

The webhook adapter still comes up: translate emits the ``handoff`` route
whenever WEBHOOK_SECRET_MCP is set (bootstrap/translate.py, the "Async handoff
route" block), and the runner sets it to a per-run random value.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

SLUG = "boot-harness"
SOURCE_SLUG = "smd-staging"
NOBODY = "nobody@boot-harness.invalid"
_DROPPED_KEYS = ("connectors", "webhook_triggers", "mcp_connector")


def _deslug(text: str) -> str:
    return text.replace(SOURCE_SLUG, SLUG)


def _scrub_scope(scope: dict[str, Any]) -> None:
    scope["inbound_allow_from"] = [NOBODY]
    scope["admins"] = [NOBODY]
    scope["trusted_sender_domains"] = ["boot-harness.invalid"]
    for key in ("device_senders", "staff_send_as"):
        scope.pop(key, None)


def _scrub_personas(personas: list[dict[str, Any]]) -> None:
    for persona in personas:
        persona.pop("cron", None)
        for skill in persona.get("skills") or []:
            settings = skill.get("settings")
            if isinstance(settings, dict) and "scheduled_recipients" in settings:
                settings["scheduled_recipients"] = NOBODY


def derive(source_text: str) -> dict[str, Any]:
    """The harness document from staging's customer.yaml text."""
    doc = yaml.safe_load(_deslug(source_text)) or {}
    if doc.get("customer_id") != SLUG:
        raise ValueError(f"source is not {SOURCE_SLUG}'s customer.yaml (customer_id={doc.get('customer_id')!r})")
    for key in _DROPPED_KEYS:
        doc.pop(key, None)
    doc["customer_name"] = "SMD boot harness (throwaway, not a seat)"
    _scrub_scope(doc.setdefault("scope", {}))
    _scrub_personas(doc.get("personas") or [])
    return doc


def render(operator_root: Path) -> str:
    source = operator_root / "customers" / SOURCE_SLUG / "customer.yaml"
    header = (
        "# GENERATED by operator/bin/boot-harness fixture from "
        f"customers/{SOURCE_SLUG}/customer.yaml. Throwaway; never published to R2.\n"
    )
    return header + yaml.safe_dump(derive(source.read_text(encoding="utf-8")), sort_keys=False)


def reachable_addresses(doc: dict[str, Any]) -> list[str]:
    """Every string in the document that looks like an email address outside .invalid."""
    found: list[str] = []

    def walk(node: Any) -> None:
        if isinstance(node, dict):
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)
        elif isinstance(node, str) and "@" in node and not node.split("@")[-1].endswith(".invalid"):
            found.append(node)

    walk(doc)
    return found
