"""The harness customer.yaml: smd-staging's shape with every reach into the world removed.

Derived, not hand-copied, so the harness boots what staging boots today (same
persona, skills, entitlements, output classes, machine size) and cannot drift
from it unnoticed. What is changed, and why:

* the slug becomes ``boot-harness`` everywhere, so no path, R2 prefix, D1
  namespace or vectorize index names staging's;
* ``connectors``, ``webhook_triggers`` and ``mcp_connector`` are dropped: the
  msgraph connector would poll staging's real test mailbox and act on it;
* every human address (roster, admins, device senders, send-as, the smd-note
  recipient) becomes an address under ``.invalid``, so no real person is
  reachable even if a send path somehow ran.

The webhook adapter still comes up: translate emits the ``handoff`` route
whenever WEBHOOK_SECRET_MCP is set (bootstrap/translate.py, the "Async handoff
route" block), and the runner sets it to a per-run random value.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

SLUG = "boot-harness"
SOURCE_SLUG = "smd-staging"
# A 1 GB seat's shape (ring 2: scott, brokery, captain-mark run shared-cpu-1x /
# 1024 MB, the size of the 2026-09-01 startup-watchdog crash loop). scott carries
# no medchron or litigation lane, so no lane-memory check applies at 1 GB.
SOURCE_1GB = "scott"
NOBODY = "nobody@boot-harness.invalid"
_DROPPED_KEYS = ("connectors", "webhook_triggers", "mcp_connector", "telegram", "record_stores")


def _deslug(text: str, source: str) -> str:
    # Only staging's slug is distinctive enough to replace textually; any other
    # source is re-homed structurally (_rehome), so a short slug like "scott"
    # never rewrites an unrelated word.
    return text.replace(SOURCE_SLUG, SLUG) if source == SOURCE_SLUG else text


def _rehome(doc: dict[str, Any]) -> None:
    """Every slug-derived binding names the harness, never the source seat."""
    doc["customer_id"] = SLUG
    doc["memory"] = {
        "d1_namespace": SLUG,
        "r2_vault_path": f"vaults/{SLUG}/",
        "vectorize_index": f"hermes-{SLUG}-vault",
    }
    if "voice_library" in doc:
        doc["voice_library"] = {"samples_path": f"r2://vaults/{SLUG}/voice/samples/"}
    for user in doc.get("users") or []:
        user["email"] = NOBODY
    escalation = doc.get("escalation")
    if isinstance(escalation, dict):
        for key in ("red_flag_recipients", "failure_recipients"):
            if key in escalation:
                escalation[key] = [NOBODY]


def _scrub_scope(scope: dict[str, Any]) -> None:
    scope["inbound_allow_from"] = [NOBODY]
    scope["admins"] = [NOBODY]
    scope["trusted_sender_domains"] = ["boot-harness.invalid"]
    for key in ("device_senders", "staff_send_as"):
        scope.pop(key, None)


# A real calendar slot that never falls inside a harness run (03:00 UTC on 1 Jan),
# so a kept routine is materialized as the seat's is but never wakes the model.
NEVER_IN_A_RUN = "0 3 1 1 *"


def _scrub_personas(personas: list[dict[str, Any]], keep_routines: bool = False) -> None:
    for persona in personas:
        if keep_routines:
            for entry in persona.get("cron") or []:
                if isinstance(entry, dict):
                    entry["schedule"] = NEVER_IN_A_RUN
        else:
            persona.pop("cron", None)
        for skill in persona.get("skills") or []:
            settings = skill.get("settings")
            if isinstance(settings, dict) and "scheduled_recipients" in settings:
                settings["scheduled_recipients"] = NOBODY


def derive(source_text: str, source: str = SOURCE_SLUG, keep_routines: bool = False) -> dict[str, Any]:
    """The harness document from a source seat's customer.yaml text."""
    doc = yaml.safe_load(_deslug(source_text, source)) or {}
    if doc.get("customer_id") not in (SLUG, source):
        raise ValueError(f"source is not {source}'s customer.yaml (customer_id={doc.get('customer_id')!r})")
    _rehome(doc)
    for key in _DROPPED_KEYS:
        doc.pop(key, None)
    doc["customer_name"] = "SMD boot harness (throwaway, not a seat)"
    _scrub_scope(doc.setdefault("scope", {}))
    _scrub_personas(doc.get("personas") or [], keep_routines)
    return doc


def render(operator_root: Path, source_slug: str = SOURCE_SLUG, keep_routines: bool = False) -> str:
    source = operator_root / "customers" / source_slug / "customer.yaml"
    header = (
        "# GENERATED by operator/bin/boot-harness fixture from "
        f"customers/{source_slug}/customer.yaml. Throwaway; never published to R2.\n"
    )
    return header + yaml.safe_dump(
        derive(source.read_text(encoding="utf-8"), source_slug, keep_routines), sort_keys=False
    )


def reachable_addresses(doc: dict[str, Any]) -> list[str]:
    """Every string in the document that looks like an email address outside .invalid."""
    found: list[str] = []

    def walk(node: Any) -> None:
        if isinstance(node, dict):
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)
        elif isinstance(node, str) and "@" in node and not node.split("@")[-1].endswith(".invalid"):
            found.append(node)

    walk(doc)
    return found
