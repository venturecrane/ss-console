"""Where the sites are (never what they do).

The FILE rules are the sprawl census's (scripts/sprawl/concepts.ts), restated
here so the capture runs in the bare Python CI job; tests/
seat-config-callers.test.ts holds the two lists in step (a file whose every site
now calls a shared reader stays here after the census drops it). Within a file, a SITE is
the smallest callable unit around the call: a module-level function, or a
method of a module-level class (a nested function is reached through the
function that holds it). Code at module level is an `inline` site, run by
importing the module (or running it as a script when it sits under
`if __name__ == "__main__":`).

A site migrated to the one shared reader (wave 2, B1) is the same site: a call
to `seat_config.load(` / `seat_config.parse(` is a customer.yaml parse, a call
to a `broker_socket` function that opens the socket is a broker socket client
(the frame encoder and the reply reader are helpers, as json.dumps was), and a call to
`seat_config.slug(` is a slug read. Only the call text in its row changes; what
it does is held to the row it had. The readers' own sources
(READER_MODULES in the manifest) are the readers, not callers, and are not sites.
"""

from __future__ import annotations

import ast
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from .inputs import SLUG_VAR

# scripts/sprawl/analyze.ts TEST_PATH, sources.ts SKIP, concepts.ts COMMENT_LINE.
TEST_PATH = re.compile(r"(^|/)tests?/|(^|/)test_[^/]*$|\.test\.[a-z]+$|_test\.py$|(^|/)conftest\.py$")
SKIP = re.compile(r"(^|/)(node_modules|dist|\.venv|__pycache__|fixtures)/")
COMMENT_LINE = re.compile(r"^\s*(#|//|/\*|\*)")
GENERATED = re.compile(r"GENERATED by (\S+?)(?=[\s,;:]|\.\s|\.$|$)", re.M)
MANIFEST = "operator/contracts/skill-shared-modules.yaml"
SELF_DIR = "operator/bin/lib/seat_callers/"

YAML_LOAD = re.compile(r"\b(yaml\.(safe_)?load|safe_load)\(")
#: The shared readers (operator/contracts/skill-shared-modules.yaml modules) and the calls into them.
READER_MODULES = ("seat_config", "broker_socket")
READER_YAML = re.compile(r"\bseat_config\.(load|parse)\(")
#: The broker_socket functions that open the socket: a call to one is a client site (encode and
#: read_reply are helpers a site uses around its own connect, as a site used json.dumps before).
SOCKET_TRANSPORT = ("connect", "request", "send_frame", "unix_stream")
READER_SOCKET = re.compile(r"\bbroker_socket\.(" + "|".join(SOCKET_TRANSPORT) + r")\(")
READER_SLUG = re.compile(r"\bseat_config\.slug\(")
NAMES_CUSTOMER_YAML = re.compile(r"customer[._]ya?ml", re.I)
SLUG = SLUG_VAR


@dataclass
class SiteSpec:
    concept: str
    file: str
    qualname: str | None
    kind: str  # function | module | script
    line: int
    assign: str | None = None
    bind: dict[str, str] = field(default_factory=dict)
    calls: list[dict] = field(default_factory=list)


def _stamped(repo: Path) -> set[str]:
    try:
        doc = yaml.safe_load((repo / MANIFEST).read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError):
        return set()
    out: set[str] = set()
    for name, body in ((doc or {}).get("modules") or {}).items():
        if not isinstance(body, dict):
            continue
        if name in READER_MODULES and isinstance(body.get("source"), str):
            out.add(body["source"])
        if isinstance(body.get("copy_as"), str) and isinstance(body.get("skills"), list):
            out |= {f"operator/skills/{s}/{body['copy_as']}" for s in body["skills"] if isinstance(s, str)}
        out |= {p for p in body.get("copies") or [] if isinstance(p, str)}
    return out


def sources(repo: Path) -> dict[str, str]:
    """Non-test, hand-written Python under operator/, as the census reads it."""
    raw = subprocess.run(["git", "ls-files", "-z", "operator"], cwd=repo, capture_output=True, check=True).stdout
    tracked = {p for p in raw.decode().split("\0") if p}
    stamped = _stamped(repo)
    out = {}
    for rel in sorted(tracked):
        if (
            not rel.endswith(".py")
            or SKIP.search(rel)
            or TEST_PATH.search(rel)
            or rel in stamped
            or rel.startswith(SELF_DIR)
        ):
            continue
        try:
            text = (repo / rel).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        head = "\n".join(text.split("\n")[:10])
        m = GENERATED.search(head)
        if m and m.group(1) in tracked:
            continue
        out[rel] = text
    return out


def _code(text: str) -> str:
    return "\n".join(line for line in text.split("\n") if not COMMENT_LINE.match(line))


def file_matches(concept: str, text: str) -> bool:
    code = _code(text)
    if concept == "customer-yaml":
        if READER_YAML.search(code):
            return True
        return bool(YAML_LOAD.search(code)) and bool(NAMES_CUSTOMER_YAML.search(code))
    if concept == "broker-socket":
        if READER_SOCKET.search(code):
            return True
        lines = code.split("\n")
        return any("AF_UNIX" in line for line in lines) and any(".connect(" in line for line in lines)
    if READER_SLUG.search(code):
        return True
    return SLUG in code and ("environ" in code or "getenv" in code)


def _reader_call(node: ast.Call, module: str, names: tuple[str, ...] | None = None) -> bool:
    """``<module>.<name>(...)``: a call into one of the shared readers."""
    f = node.func
    return (
        isinstance(f, ast.Attribute)
        and isinstance(f.value, ast.Name)
        and f.value.id == module
        and (names is None or f.attr in names)
    )


def _is_yaml_load(node: ast.Call) -> bool:
    if _reader_call(node, "seat_config", ("load", "parse")):
        return True
    f = node.func
    if isinstance(f, ast.Attribute) and f.attr in ("load", "safe_load"):
        return isinstance(f.value, ast.Name) and "yaml" in f.value.id.lower()
    return isinstance(f, ast.Name) and f.id == "safe_load"


def _is_connect(node: ast.Call) -> bool:
    if _reader_call(node, "broker_socket", SOCKET_TRANSPORT):
        return True
    return isinstance(node.func, ast.Attribute) and node.func.attr == "connect"


def _constants(tree: ast.Module) -> dict[str, object]:
    out: dict[str, object] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    out[t.id] = node.value.value
    return out


def _names_slug(key: ast.AST, consts: dict[str, object], unit_src: str) -> bool:
    if isinstance(key, ast.Constant):
        return key.value == SLUG
    if isinstance(key, ast.Name):
        quoted = f'"{SLUG}"' in unit_src or f"'{SLUG}'" in unit_src
        return consts.get(key.id) == SLUG or (key.id not in consts and quoted)
    return False


def _env_key(node: ast.AST) -> ast.AST | None:
    """The key of an environment read: environ.get(k), getenv(k), environ[k]."""
    if isinstance(node, ast.Call) and node.args:
        f = node.func
        if isinstance(f, ast.Attribute) and f.attr == "get" and ast.unparse(f.value).endswith("environ"):
            return node.args[0]
        if (isinstance(f, ast.Attribute) and f.attr == "getenv") or (isinstance(f, ast.Name) and f.id == "getenv"):
            return node.args[0]
    if (
        isinstance(node, ast.Subscript)
        and ast.unparse(node.value).endswith("environ")
        and isinstance(node.ctx, ast.Load)
    ):
        return node.slice
    return None


def _env_helpers(tree: ast.Module) -> dict[str, str]:
    """Module functions that read the environment by their first parameter: {name: parameter}."""
    out = {}
    for node in tree.body:
        if not isinstance(node, ast.FunctionDef) or not node.args.args:
            continue
        param = node.args.args[0].arg
        for sub in ast.walk(node):
            key = _env_key(sub)
            if isinstance(key, ast.Name) and key.id == param:
                out[node.name] = param
                break
    return out


def _helper_sites(rel: str, tree: ast.Module, text: str) -> list[SiteSpec]:
    """`helper("CUSTOMER_SLUG")` where helper reads os.environ by its parameter: the helper, bound to the name."""
    helpers, consts = _env_helpers(tree), _constants(tree)
    calls: dict[str, list[dict]] = {}
    for node in ast.walk(tree):
        if not (
            isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in helpers and node.args
        ):
            continue
        key = node.args[0]
        named = (
            key.value if isinstance(key, ast.Constant) else consts.get(key.id) if isinstance(key, ast.Name) else None
        )
        if named == SLUG:
            calls.setdefault(node.func.id, []).append(
                {"line": node.lineno, "expr": ast.get_source_segment(text, node) or ""}
            )
    return [
        SiteSpec("slug", rel, name, "function", min(c["line"] for c in found), bind={helpers[name]: SLUG}, calls=found)
        for name, found in sorted(calls.items())
    ]


def _units(tree: ast.Module) -> list[tuple[str | None, ast.AST, ast.stmt]]:
    """(qualname or None, unit node, top-level statement) for every top-level statement."""
    out: list[tuple[str | None, ast.AST, ast.stmt]] = []
    for stmt in tree.body:
        if isinstance(stmt, ast.FunctionDef | ast.AsyncFunctionDef):
            out.append((stmt.name, stmt, stmt))
        elif isinstance(stmt, ast.ClassDef):
            for sub in stmt.body:
                if isinstance(sub, ast.FunctionDef | ast.AsyncFunctionDef):
                    out.append((f"{stmt.name}.{sub.name}", sub, stmt))
                else:
                    out.append((None, sub, stmt))
        else:
            out.append((None, stmt, stmt))
    return out


def _is_main_guard(stmt: ast.stmt) -> bool:
    return isinstance(stmt, ast.If) and "__name__" in ast.unparse(stmt.test) and "__main__" in ast.unparse(stmt.test)


def _hits(concept: str, unit: ast.AST, consts: dict[str, object], text: str) -> list[ast.AST]:
    unit_src = ast.get_source_segment(text, unit) or ""
    found = []
    for node in ast.walk(unit):
        if concept == "customer-yaml" and isinstance(node, ast.Call) and _is_yaml_load(node):
            found.append(node)
        elif concept == "broker-socket" and isinstance(node, ast.Call) and _is_connect(node):
            found.append(node)
        elif concept == "slug" and isinstance(node, ast.Call) and _reader_call(node, "seat_config", ("slug",)):
            found.append(node)
        elif concept == "slug":
            key = _env_key(node)
            if key is not None and _names_slug(key, consts, unit_src):
                found.append(node)
    return found


def _site_for(concept: str, rel: str, qualname: str | None, stmt: ast.stmt, hits: list[ast.AST], text: str) -> SiteSpec:
    calls = [{"line": getattr(h, "lineno", 0), "expr": ast.get_source_segment(text, h) or ast.unparse(h)} for h in hits]
    line = min(c["line"] for c in calls)
    if qualname is not None:
        return SiteSpec(concept, rel, qualname, "function", line, calls=calls)
    if _is_main_guard(stmt):
        return SiteSpec(concept, rel, None, "script", line, calls=calls)
    assign = None
    if isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 and isinstance(stmt.targets[0], ast.Name):
        assign = stmt.targets[0].id
    elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
        assign = stmt.target.id
    return SiteSpec(concept, rel, None, "module", line, assign=assign, calls=calls)


def sites_in(concept: str, rel: str, text: str) -> list[SiteSpec]:
    tree = ast.parse(text)
    consts = _constants(tree)
    grouped: dict[tuple, tuple[str | None, ast.stmt, list[ast.AST]]] = {}
    for qualname, unit, stmt in _units(tree):
        hits = _hits(concept, unit, consts, text)
        if not hits:
            continue
        key = (qualname,) if qualname else ("<module>", stmt.lineno)
        grouped.setdefault(key, (qualname, stmt, []))[2].extend(hits)
    found = [_site_for(concept, rel, q, s, h, text) for q, s, h in grouped.values()]
    if concept == "slug":
        found += _helper_sites(rel, tree, text)
    return found


CONCEPTS = ("customer-yaml", "broker-socket", "slug")


def discover(repo: Path) -> tuple[dict[str, list[str]], list[SiteSpec]]:
    """(matching files per concept, every site)."""
    files: dict[str, list[str]] = {c: [] for c in CONCEPTS}
    sites: list[SiteSpec] = []
    for rel, text in sources(repo).items():
        for concept in CONCEPTS:
            if not file_matches(concept, text):
                continue
            found = sites_in(concept, rel, text)
            # The census rules are textual for the yaml and socket concepts; a slug read is a site or nothing.
            if found or concept != "slug":
                files[concept].append(rel)
            sites.extend(found)
    return files, sites
