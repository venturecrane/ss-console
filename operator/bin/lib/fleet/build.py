ARTIFACT_PATHS = {
    "image-manifest.json": "app/image-manifest.json",
    "image-capabilities.json": "app/image-capabilities.json",
    "_env-arrays.generated.sh": "app/_env-arrays.generated.sh",
}
LAYER_SIZE_CAP = 64 * 1024 * 1024
LANE_SCHEMA_MODULES = {
    "medchron": "operator/runners/medchron/medchron/config.py",
    "demand": "operator/runners/medchron/medchron/demand/firm.py",
    "drafting": "operator/runners/medchron/medchron/drafting/firm.py",
    "litigation": "operator/runners/medchron/medchron/litigation/firm.py",
}
BUILD_TOML = """# Generated by `operator/bin/fleet build`: the registry app's build-only config.
app = "{app}"
[build]
  dockerfile = "../../templates/Dockerfile"
"""


def dockerfile_arg(dockerfile: str, name: str) -> str | None:
    m = re.search(rf'^ARG {name}="?([0-9A-Za-z.@_-]+)"?\s*$', dockerfile, re.MULTILINE)
    return m.group(1) if m else None


def required_env_from_arrays(text: str) -> list[str]:
    m = re.search(r"^REQUIRED_ENV=\((.*?)^\)", text, re.MULTILINE | re.DOTALL)
    if not m:
        raise ToolingError("no REQUIRED_ENV=( ... ) array in _env-arrays.generated.sh")
    return sorted(tok for tok in m.group(1).split() if ids.SECRET_NAME_RE.match(tok))


def lane_inputs(repo: Path) -> dict[str, str]:
    return {
        lane: hashlib.sha256((repo / rel).read_bytes()).hexdigest()
        for lane, rel in LANE_SCHEMA_MODULES.items()
        if (repo / rel).is_file()
    }


@dataclass
class BuildOptions:
    notes: str = ""
    declared_secrets: tuple[str, ...] = ()
    volume_forward_compatible: bool = True


REGISTRY_HOST = ids.FLEET_REGISTRY.split("/", 1)[0]
ZSTD_MAGIC = b"\x28\xb5\x2f\xfd"
# How long a just-pushed image is given to become visible at the registry's
# manifest endpoint before the build records no capabilities: the waits between
# attempts, about four minutes in all. The first folded image (2026-10-23,
# img-202610230344-b39e3bf5) came back HTTP 404 on the single GET the build made
# seconds after the push and `fleet artifacts` had to re-read it by hand; the
# remote builder's push and the registry's index are not one write.
MANIFEST_RETRY_DELAYS_S: tuple[float, ...] = (15.0, 30.0, 60.0, 120.0)
MANIFEST_ACCEPT = ", ".join(
    (
        "application/vnd.oci.image.manifest.v1+json",
        "application/vnd.docker.distribution.manifest.v2+json",
    )
)


class RegistryNotReady(ToolingError):
    """The registry answered 404 for a manifest: the image is not visible there (yet)."""


class ImageExtractor:
    """Read named files out of a pushed image, small layers first-from-the-top.

    Talks to the registry's v2 HTTP API directly with the Fly auth token
    (Basic, any username). It deliberately does not shell out to `crane`: on
    SMD laptops that name is the crane VENTURE launcher, not
    go-containerregistry, and the first real build (2026-10-19) recorded no
    capabilities because of it.
    """

    def __init__(
        self,
        runner: Runner,
        sleep: Callable[[float], None] = time.sleep,
        log: Callable[[str], None] | None = None,
    ) -> None:
        self.runner = runner
        self.sleep = sleep
        self.log = log or (lambda _line: None)
        self._token: str | None = None

    def extract(self, ref: str) -> dict[str, bytes]:
        repo, digest = ref.split("@", 1)
        repo = repo.rsplit(":", 1)[0]
        man = json.loads(self._manifest_when_visible(repo, digest))
        wanted = {v: k for k, v in ARTIFACT_PATHS.items()}
        found: dict[str, bytes] = {}
        for layer in reversed(man.get("layers") or []):
            missing = {path for path, name in wanted.items() if name not in found}
            if not missing:
                break
            if int(layer.get("size") or 0) > LAYER_SIZE_CAP:
                continue
            for member, data in self._members(self._blob(f"{repo}@{layer['digest']}"), missing):
                found.setdefault(wanted[member], data)
        return found

    def _auth(self) -> str:
        if self._token is None:
            tok = require_ok(self.runner.run(["fly", "auth", "token"], timeout=60), "fly auth token").stdout.strip()
            if not tok:
                raise ToolingError("fly auth token printed nothing")
            self._token = tok
        return "Basic " + base64.b64encode(f"x:{self._token}".encode()).decode()

    def _get(self, host: str, path: str, accept: str | None = None) -> bytes:
        """HTTPS GET on the registry host; one https redirect (the blob store) is followed without auth."""
        if host != REGISTRY_HOST or not path.startswith("/v2/"):
            raise ToolingError(f"refusing a non-registry request {host}{path}")
        headers = {"Authorization": self._auth()}
        if accept:
            headers["Accept"] = accept
        try:
            status, location, body = _https_get(host, path, headers)
            if status in (301, 302, 303, 307, 308) and location:
                target = urllib.parse.urlsplit(location)
                if target.scheme != "https" or not target.hostname:
                    raise ToolingError(f"refusing a non-https redirect from {path}")
                status, _, body = _https_get(
                    target.hostname, target.path + ("?" + target.query if target.query else ""), {}
                )
        except (OSError, http.client.HTTPException) as exc:
            raise ToolingError(f"registry GET {path} failed: {exc}") from exc
        if status == 404:
            raise RegistryNotReady(f"registry GET {path} returned HTTP 404 (not visible at the registry)")
        if status != 200:
            raise ToolingError(f"registry GET {path} returned HTTP {status}")
        return body

    def _manifest_when_visible(self, repo: str, digest: str) -> bytes:
        """The manifest, waiting out registry propagation: a 404 is retried on
        MANIFEST_RETRY_DELAYS_S and only the last one is an error. Any other
        failure is raised at once; a 404 for a digest that was never pushed
        costs the whole schedule, which is the price of not guessing."""
        for attempt, delay in enumerate(MANIFEST_RETRY_DELAYS_S + (None,), start=1):
            try:
                return self._manifest(repo, digest)
            except RegistryNotReady as exc:
                if delay is None:
                    waited = int(sum(MANIFEST_RETRY_DELAYS_S))
                    raise ToolingError(f"{exc} after {attempt} attempts over {waited}s") from exc
                self.log(f"image not visible at the registry yet (attempt {attempt}); retrying in {int(delay)}s")
                self.sleep(delay)
        raise AssertionError("unreachable")

    @staticmethod
    def _split(repo: str) -> tuple[str, str]:
        host, _, name = repo.partition("/")
        return host, name

    def _manifest(self, repo: str, digest: str) -> bytes:
        host, name = self._split(repo)
        return self._get(host, f"/v2/{name}/manifests/{digest}", MANIFEST_ACCEPT)

    def _blob(self, ref: str) -> bytes:
        repo, digest = ref.split("@", 1)
        host, name = self._split(repo)
        return self._get(host, f"/v2/{name}/blobs/{digest}")

    @staticmethod
    def _members(blob: bytes, names: set[str]) -> list[tuple[str, bytes]]:
        out = []
        if blob[:4] == ZSTD_MAGIC:
            # The Fly/Depot builder pushes tar+zstd layers, which tarfile cannot open.
            blob = _zstd_decompress(blob)
        with tarfile.open(fileobj=io.BytesIO(blob), mode="r:*") as tar:
            for info in tar:
                name = info.name.lstrip("./")
                if name in names and info.isfile():
                    fh = tar.extractfile(info)
                    if fh is not None:
                        out.append((name, fh.read()))
        return out


def _zstd_decompress(blob: bytes) -> bytes:
    try:
        from compression import zstd  # Python 3.14+

        return zstd.decompress(blob)
    except ImportError:
        pass
    exe = shutil.which("zstd")
    if not exe:
        raise ToolingError("this layer is zstd-compressed: needs Python 3.14+ or the zstd CLI")
    proc = subprocess.run([exe, "-dc"], input=blob, capture_output=True, timeout=600, check=False)  # noqa: S603 - fixed argv from shutil.which; the blob goes on stdin, no shell
    if proc.returncode != 0:
        raise ToolingError(f"zstd -dc failed: {proc.stderr.decode(errors='replace')[-300:]}")
    return proc.stdout


def _https_get(host: str, path: str, headers: dict[str, str]) -> tuple[int, str | None, bytes]:
    ctx = ssl.create_default_context()
    conn = http.client.HTTPSConnection(host, timeout=600, context=ctx)  # nosemgrep: python.lang.security.audit.httpsconnection-detected.httpsconnection-detected - Python 3.13 with an explicit default context verifies certificates and hostnames  # fmt: skip
    try:
        conn.request("GET", path, headers=headers)
        resp = conn.getresponse()
        return resp.status, resp.getheader("Location"), resp.read()
    finally:
        conn.close()


class Builder:
    def __init__(
        self,
        repo: Path,
        runner: Runner,
        fly: Fly,
        store: FleetStore,
        r2: R2,
        extractor: ImageExtractor,
        log: Callable[[str], None],
    ) -> None:
        self.repo, self.runner, self.fly, self.store, self.r2, self.extractor, self.log = (
            repo,
            runner,
            fly,
            store,
            r2,
            extractor,
            log,
        )

    def guard(self) -> None:
        res = self.runner.run(
            ["bash", str(self.repo / "operator/bin/lib/build-source-guard.sh"), str(self.repo)], timeout=180
        )
        for line in res.text.strip().splitlines():
            self.log(line)
        if not res.ok:
            raise Refusal("the build source guard refused (above); nothing was built")

    def pins(self) -> dict[str, str]:
        """The two shas an image is built from.

        ``overlay_ref`` IS ``ss_console_sha`` since the fold (ADR 0095): the overlay
        is built from this tree, the Dockerfile bakes the commit as SMD_OVERLAY_REF,
        and the heartbeat reports it as ``version``. The key keeps its name because
        ``fleet_releases.overlay_ref`` is the column the smoke's heartbeat check
        (``smoke.judge_row``) compares against; it records the code sha a seat on
        this release must echo.
        """
        dockerfile = (self.repo / "operator/templates/Dockerfile").read_text(encoding="utf-8")
        ss_sha = require_ok(
            self.runner.run(["git", "-C", str(self.repo), "rev-parse", "HEAD"]), "git rev-parse"
        ).stdout.strip()
        hermes = dockerfile_arg(dockerfile, "HERMES_UPSTREAM_SHA") or ""
        if not (ids.SHA_RE.match(ss_sha) and ids.SHA_RE.match(hermes)):
            raise Refusal(f"could not read 40-hex pins (ss-console {ss_sha!r}, hermes {hermes!r})")
        return {"ss_console_sha": ss_sha, "overlay_ref": ss_sha, "hermes_sha": hermes}

    def ensure_registry_app(self) -> None:
        if not self.fly.app_exists(ids.FLEET_REGISTRY_APP):
            self.log(f"creating the registry app {ids.FLEET_REGISTRY_APP} (no Machines)")
            self.fly.create_app(ids.FLEET_REGISTRY_APP)

    def build(self, opts: BuildOptions) -> dict[str, Any]:
        for name in opts.declared_secrets:
            ids.secret_name(name)
        self.guard()
        pins = self.pins()
        stamp = datetime.now(timezone.utc).strftime("%Y%m%d%H%M")
        label = f"rel-{pins['ss_console_sha'][:8]}-{stamp}"
        self.ensure_registry_app()
        toml_path = self.repo / "operator/.rendered/_fleet/fly.toml"
        toml_path.parent.mkdir(parents=True, exist_ok=True)
        toml_path.write_text(BUILD_TOML.format(app=ids.FLEET_REGISTRY_APP), encoding="utf-8")
        self.log(f"building {label} (remote builder; cached layers make a code-only release short)")
        res = self.fly.build_push(str(toml_path), label, pins["ss_console_sha"])
        require_ok(res, "fly deploy --build-only --push")
        image_ref = f"{ids.FLEET_REGISTRY}:{label}"
        digest = digest_from_build_output(res.text)
        if not digest:
            raise ToolingError("could not read the pushed image digest from the build output")
        release = {
            "release_id": f"img-{stamp}-{pins['ss_console_sha'][:8]}",
            "kind": "image", "image_ref": image_ref, "image_digest": ids.digest(digest),
            "ss_console_sha": pins["ss_console_sha"], "overlay_ref": pins["overlay_ref"],
            "volume_forward_compatible": 1 if opts.volume_forward_compatible else 0,
            "declared_secrets": json.dumps(sorted(opts.declared_secrets)), "notes": opts.notes or None,
        }  # fmt: skip
        self.upload_artifacts(release, pins)
        self.store.insert_release(release)
        self.log(f"release {release['release_id']}: {image_ref} {digest}")
        return release

    def upload_artifacts(self, release: dict[str, Any], pins: dict[str, str]) -> None:
        digest = release["image_digest"]
        try:
            files = self.extractor.extract(f"{release['image_ref']}@{digest}")
        except (ToolingError, OSError, ValueError, tarfile.TarError, json.JSONDecodeError) as exc:
            self.log(f"WARN: could not read artifacts out of the image ({exc}); recording without capabilities")
            files = {}
        arrays = (
            files.get("_env-arrays.generated.sh")
            or (self.repo / "operator/templates/_env-arrays.generated.sh").read_bytes()
        )
        source = "image" if "_env-arrays.generated.sh" in files else "checkout (same commit; the image COPYs this file)"
        self.r2.put_json(
            image_key(digest, "required-env.json"),
            {"required": required_env_from_arrays(arrays.decode()), "source": source},
        )
        self.r2.put_json(image_key(digest, "lane-inputs.json"), lane_inputs(self.repo))
        for name in ("image-manifest.json", "image-capabilities.json"):
            if name in files:
                self.r2.put_bytes(image_key(digest, name), files[name])
            else:
                self.log(f"WARN: {name} not found in the image; skills releases to this image will refuse")
        self.r2.put_json(image_key(digest, "release.json"), {**release, "hermes_sha": pins["hermes_sha"]})
