"""`fleet build`: one image for every seat, built once into the Fly registry.

1. Source guard: lib/build-source-guard.sh, the same refusal a from-source
   provision makes (dirty tree, behind origin/main, OVERLAY_REF disagreeing
   with overlay-pairs.json).
2. The registry app ``hermes-fleet`` (no Machines) exists, or is created.
3. ``fly deploy --build-only --push --remote-only -a hermes-fleet`` with the
   label rel-<ss8>-<overlay8>-<utc minute>; the only build-arg is
   SS_CONSOLE_SHA (the Hermes and overlay pins are the Dockerfile's own).
4. The release's artifacts go to R2 fleet/images/<digest-hex>/:
     image-manifest.json, image-capabilities.json and required-env.json are
     READ OUT OF THE BUILT IMAGE with `crane` (only the small layers that
     carry them are fetched), because they describe the image, not this
     checkout; lane-inputs.json is computed here from the runner's
     schema modules, which is exact because step 1 proved this checkout IS
     the build source. If crane cannot read the image, the build is
     recorded WITHOUT capabilities (and with required-env generated from
     this checkout's _env-arrays.generated.sh, the file the image COPYs):
     image releases still work, skills releases to that image refuse.
5. fleet_releases row (kind image).
"""

from __future__ import annotations

import hashlib
import io
import json
import re
import subprocess
import tarfile
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable

from . import ids
from .d1 import FleetStore
from .fly import Fly, digest_from_build_output
from .r2 import R2, image_key
from .runner import Refusal, Runner, ToolingError, require_ok

ARTIFACT_PATHS = {
    "image-manifest.json": "app/image-manifest.json",
    "image-capabilities.json": "app/image-capabilities.json",
    "_env-arrays.generated.sh": "app/_env-arrays.generated.sh",
}
LAYER_SIZE_CAP = 64 * 1024 * 1024
LANE_SCHEMA_MODULES = {
    "medchron": "operator/runners/medchron/medchron/config.py",
    "demand": "operator/runners/medchron/medchron/demand/firm.py",
    "drafting": "operator/runners/medchron/medchron/drafting/firm.py",
    "litigation": "operator/runners/medchron/medchron/litigation/firm.py",
}
BUILD_TOML = """# Generated by `operator/bin/fleet build`: the registry app's build-only config.
app = "{app}"
[build]
  dockerfile = "../../templates/Dockerfile"
"""


def dockerfile_arg(dockerfile: str, name: str) -> str | None:
    m = re.search(rf'^ARG {name}="?([0-9A-Za-z.@_-]+)"?\s*$', dockerfile, re.MULTILINE)
    return m.group(1) if m else None


def required_env_from_arrays(text: str) -> list[str]:
    m = re.search(r"^REQUIRED_ENV=\((.*?)^\)", text, re.MULTILINE | re.DOTALL)
    if not m:
        raise ToolingError("no REQUIRED_ENV=( ... ) array in _env-arrays.generated.sh")
    return sorted(tok for tok in m.group(1).split() if ids.SECRET_NAME_RE.match(tok))


def lane_inputs(repo: Path) -> dict[str, str]:
    return {
        lane: hashlib.sha256((repo / rel).read_bytes()).hexdigest()
        for lane, rel in LANE_SCHEMA_MODULES.items()
        if (repo / rel).is_file()
    }


@dataclass
class BuildOptions:
    notes: str = ""
    declared_secrets: tuple[str, ...] = ()
    volume_forward_compatible: bool = True


class ImageExtractor:
    """Read named files out of a pushed image, small layers first-from-the-top."""

    def __init__(self, runner: Runner) -> None:
        self.runner = runner

    def extract(self, ref: str) -> dict[str, bytes]:
        man = json.loads(require_ok(self.runner.run(["crane", "manifest", ref], timeout=120), "crane manifest").stdout)
        wanted = {v: k for k, v in ARTIFACT_PATHS.items()}
        found: dict[str, bytes] = {}
        repo = ref.split("@", 1)[0].rsplit(":", 1)[0]
        for layer in reversed(man.get("layers") or []):
            missing = {path for path, name in wanted.items() if name not in found}
            if not missing:
                break
            if int(layer.get("size") or 0) > LAYER_SIZE_CAP:
                continue
            for member, data in self._members(self._blob(f"{repo}@{layer['digest']}"), missing):
                found.setdefault(wanted[member], data)
        return found

    def _blob(self, ref: str) -> bytes:
        proc = subprocess.run(["crane", "blob", ref], capture_output=True, timeout=600, check=False)  # noqa: S603 - literal crane argv, no shell; ref is the digest from crane's own manifest
        if proc.returncode != 0:
            raise ToolingError(f"crane blob {ref} failed: {proc.stderr.decode(errors='replace')[-300:]}")
        return proc.stdout

    @staticmethod
    def _members(blob: bytes, names: set[str]) -> list[tuple[str, bytes]]:
        out = []
        with tarfile.open(fileobj=io.BytesIO(blob), mode="r:*") as tar:
            for info in tar:
                name = info.name.lstrip("./")
                if name in names and info.isfile():
                    fh = tar.extractfile(info)
                    if fh is not None:
                        out.append((name, fh.read()))
        return out


class Builder:
    def __init__(
        self,
        repo: Path,
        runner: Runner,
        fly: Fly,
        store: FleetStore,
        r2: R2,
        extractor: ImageExtractor,
        log: Callable[[str], None],
    ) -> None:
        self.repo, self.runner, self.fly, self.store, self.r2, self.extractor, self.log = (
            repo,
            runner,
            fly,
            store,
            r2,
            extractor,
            log,
        )

    def guard(self) -> None:
        res = self.runner.run(
            ["bash", str(self.repo / "operator/bin/lib/build-source-guard.sh"), str(self.repo)], timeout=180
        )
        for line in res.text.strip().splitlines():
            self.log(line)
        if not res.ok:
            raise Refusal("the build source guard refused (above); nothing was built")

    def pins(self) -> dict[str, str]:
        dockerfile = (self.repo / "operator/templates/Dockerfile").read_text(encoding="utf-8")
        ss_sha = require_ok(
            self.runner.run(["git", "-C", str(self.repo), "rev-parse", "HEAD"]), "git rev-parse"
        ).stdout.strip()
        overlay = dockerfile_arg(dockerfile, "OVERLAY_REF") or ""
        hermes = dockerfile_arg(dockerfile, "HERMES_UPSTREAM_SHA") or ""
        if not (ids.SHA_RE.match(ss_sha) and ids.SHA_RE.match(overlay) and ids.SHA_RE.match(hermes)):
            raise Refusal(f"could not read 40-hex pins (ss-console {ss_sha!r}, overlay {overlay!r}, hermes {hermes!r})")
        return {"ss_console_sha": ss_sha, "overlay_ref": overlay, "hermes_sha": hermes}

    def ensure_registry_app(self) -> None:
        if not self.fly.app_exists(ids.FLEET_REGISTRY_APP):
            self.log(f"creating the registry app {ids.FLEET_REGISTRY_APP} (no Machines)")
            self.fly.create_app(ids.FLEET_REGISTRY_APP)

    def build(self, opts: BuildOptions) -> dict[str, Any]:
        for name in opts.declared_secrets:
            ids.secret_name(name)
        self.guard()
        pins = self.pins()
        stamp = datetime.now(timezone.utc).strftime("%Y%m%d%H%M")
        label = f"rel-{pins['ss_console_sha'][:8]}-{pins['overlay_ref'][:8]}-{stamp}"
        self.ensure_registry_app()
        toml_path = self.repo / "operator/.rendered/_fleet/fly.toml"
        toml_path.parent.mkdir(parents=True, exist_ok=True)
        toml_path.write_text(BUILD_TOML.format(app=ids.FLEET_REGISTRY_APP), encoding="utf-8")
        self.log(f"building {label} (remote builder; cached layers make an overlay-only release short)")
        res = self.fly.build_push(str(toml_path), label, pins["ss_console_sha"])
        require_ok(res, "fly deploy --build-only --push")
        image_ref = f"{ids.FLEET_REGISTRY}:{label}"
        digest = digest_from_build_output(res.text) or self._crane_digest(image_ref)
        release = {
            "release_id": f"img-{stamp}-{pins['ss_console_sha'][:8]}-{pins['overlay_ref'][:8]}",
            "kind": "image", "image_ref": image_ref, "image_digest": ids.digest(digest),
            "ss_console_sha": pins["ss_console_sha"], "overlay_ref": pins["overlay_ref"],
            "volume_forward_compatible": 1 if opts.volume_forward_compatible else 0,
            "declared_secrets": json.dumps(sorted(opts.declared_secrets)), "notes": opts.notes or None,
        }  # fmt: skip
        self.upload_artifacts(release, pins)
        self.store.insert_release(release)
        self.log(f"release {release['release_id']}: {image_ref} {digest}")
        return release

    def _crane_digest(self, ref: str) -> str:
        return require_ok(self.runner.run(["crane", "digest", ref], timeout=120), "crane digest").stdout.strip()

    def upload_artifacts(self, release: dict[str, Any], pins: dict[str, str]) -> None:
        digest = release["image_digest"]
        # crane reads registry.fly.io with the docker credential `fly auth docker` writes.
        self.runner.run(["fly", "auth", "docker"], timeout=60)
        try:
            files = self.extractor.extract(f"{release['image_ref']}@{digest}")
        except (ToolingError, OSError, tarfile.TarError, json.JSONDecodeError) as exc:
            self.log(f"WARN: could not read artifacts out of the image ({exc}); recording without capabilities")
            files = {}
        arrays = (
            files.get("_env-arrays.generated.sh")
            or (self.repo / "operator/templates/_env-arrays.generated.sh").read_bytes()
        )
        source = "image" if "_env-arrays.generated.sh" in files else "checkout (same commit; the image COPYs this file)"
        self.r2.put_json(
            image_key(digest, "required-env.json"),
            {"required": required_env_from_arrays(arrays.decode()), "source": source},
        )
        self.r2.put_json(image_key(digest, "lane-inputs.json"), lane_inputs(self.repo))
        for name in ("image-manifest.json", "image-capabilities.json"):
            if name in files:
                self.r2.put_bytes(image_key(digest, name), files[name])
            else:
                self.log(f"WARN: {name} not found in the image; skills releases to this image will refuse")
        self.r2.put_json(image_key(digest, "release.json"), {**release, "hermes_sha": pins["hermes_sha"]})
