"""One loader for every lane's firm settings file.

Six paid lanes (the lane list is ``operator/contracts/job-lanes.yaml``) read
their firm's settings with six loaders that shared one skeleton: resolve the
inputs directory once (``firm_inputs.pin``), refuse a missing file, refuse
text that is not YAML, run the lane's own ``validate`` (and, for demand and
drafting, the pinned files' hashes), and build the lane's typed object; plus
the ``python -m jobs.<lane>.firm <dir>`` provisioning check. The skeleton lives
here once. What stays in each lane is what is genuinely its own: the declared
keys and their rules (``validate``), the typed object, its error class, and the
words its messages use.

A lane declares a :class:`FirmFile` and binds its public names to it::

    FIRM_FILE = FirmFile(env=ENV_DIR, default=DEFAULT_DIR, name=CONFIG_NAME, ...)
    resolve_dir = FIRM_FILE.resolve
    load = FIRM_FILE.load

Every message, exit code and value is the one the lane's own loader gave
(``tests/goldens/firm_config`` holds the answers).

Five lanes use it: demand and drafting, the case file and litigation, and
records. The chronology (``medchron/config.py``) still reads its file itself,
for one reason outside its behaviour: its ``yaml.safe_load`` is a row of the
seat-config caller table (``operator/contracts/seat-config-callers.json``; a
false positive, since its docstring names the seat settings file), and that
table is being regenerated by the seat-config readers change. It joins here
once that lands; ``name=None`` (the env var names the file) and ``validate``'s
path argument are its shape.
"""

from __future__ import annotations

import os
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Generic, TypeVar

import yaml

from .firm_inputs import pin

T = TypeVar("T")


class FirmConfigError(ValueError):
    """A firm settings file is missing, is not YAML, or breaks a declared rule.
    Each lane raises its own subclass, so a caller catches its lane's error
    and nothing else."""


@dataclass(frozen=True)
class FirmFile(Generic[T]):
    #: The env var naming the inputs (a directory, or with ``name`` None the file).
    env: str
    #: Where the seat delivers them when the env var is unset.
    default: str | Path
    #: The lane's error class.
    error: type[FirmConfigError]
    #: ``(data, path)``: every problem, empty when valid. The path is the file's,
    #: for a validator whose messages name it.
    validate: Callable[[Any, str], list[str]]
    #: ``(root, data)``: the typed object (``root`` is the directory, or the file
    #: when ``name`` is None). It may raise ``error``.
    build: Callable[[Path, Any], T]
    #: The settings file's name inside the directory; None when the env var and
    #: the default name the file itself.
    name: str | None = None
    #: The refusal when the file is absent, formatted with ``path``, ``env`` and
    #: ``default``.
    missing: str = "{path} not found (set {env})"
    #: ``(root, data)``: problems found only once the rules pass (the pinned
    #: files' hashes).
    check: Callable[[Path, Any], list[str]] | None = None

    def resolve(self, explicit: str | Path | None = None) -> Path:
        # Resolved once: the live path is a symlink the applier swaps (jobs/firm_inputs.py).
        return pin(explicit or os.environ.get(self.env) or self.default)

    def load(self, explicit: str | Path | None = None) -> T:
        return load(self, explicit)

    def main(self, argv: list[str] | None, *, usage: str, ok: Callable[[T], str]) -> int:
        """The provisioning check: 0 and ``ok(firm)`` on stdout when the
        settings load, 1 and the refusal on stderr when they do not, 2 and
        ``usage`` on a wrong argument count."""
        args = argv if argv is not None else sys.argv[1:]
        if len(args) != 1:
            print(usage, file=sys.stderr)
            return 2
        try:
            firm = self.load(args[0])
        except self.error as exc:
            print(str(exc), file=sys.stderr)
            return 1
        print(ok(firm))
        return 0


def load(spec: FirmFile[T], explicit: str | Path | None = None) -> T:
    """The lane's typed settings from ``explicit``, else the env var, else the
    seat's path; ``spec.error`` naming the file and every problem otherwise."""
    root = spec.resolve(explicit)
    path = root / spec.name if spec.name else root
    if not path.is_file():
        raise spec.error(spec.missing.format(path=path, env=spec.env, default=spec.default))
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise spec.error(f"{path}: not valid YAML ({exc})") from exc
    problems = spec.validate(data, str(path))
    if not problems and spec.check is not None:
        problems = spec.check(root, data)
    if problems:
        raise spec.error(f"{path}: " + "; ".join(problems))
    return spec.build(root, data)


__all__ = ["FirmConfigError", "FirmFile", "load"]
